"""
G-Code Generator for Arduino Uno GRBL 0.9i Handwriting Machine.
Generates optimized toolpaths with Servo (M3/M5) or Z-Axis (G0/G1) pen lift,
feedrate control, dwell pauses, and multi-page paper change pauses.
"""

from typing import List, Tuple, Dict, Any

def generate_gcode(
    pages: List[Dict[str, Any]],
    page_index: int = None,  # None means all pages combined with M0 pause
    pen_mode: str = "servo",  # "servo" or "z_axis"
    pen_down_cmd: str = "M5",
    pen_up_cmd: str = "M3 S90",
    z_down_pos: float = 0.0,
    z_up_pos: float = 5.0,
    feed_draw: int = 1800,
    feed_travel: int = 5000,
    invert_y: bool = False,
    flip_lab_record: bool = False,
    servo_delay_ms: int = 150,
    return_to_origin: bool = False,
    resume_from_current: bool = None
) -> str:
    """
    Generate calibrated G-code for pages.
    """
    if resume_from_current is not None:
        return_to_origin = not resume_from_current

    lines = []
    lines.append("; ==================================================")
    lines.append("; Machine: Arduino Uno (CH340C) + GRBL 0.9i")
    lines.append(f"; Pen Mode: {pen_mode.upper()} | Travel Feed: {feed_travel} | Draw Feed: {feed_draw}")
    if flip_lab_record:
        lines.append("; Mode: LAB RECORD (180° Inverted Physical Plot)")
    if not return_to_origin:
        lines.append("; Resume Mode: DIRECT FROM CURRENT/TOUCHED POSITION (No Origin Return)")
    lines.append("; Generated by Handcode Studio")
    lines.append("; ==================================================\n")

    # Initialization commands
    lines.append("G21          ; Millimeter units")
    lines.append("G90          ; Absolute positioning")
    lines.append("G94          ; Feedrate per minute mode")

    # Initial pen up
    if pen_mode == "servo":
        lines.append(f"{pen_up_cmd}         ; Pen UP")
        if servo_delay_ms > 0:
            lines.append(f"G4 P{servo_delay_ms / 1000.0:.2f}     ; Dwell for servo lift")
    else:
        lines.append(f"G0 Z{z_up_pos:.2f}     ; Pen UP")

    if return_to_origin:
        lines.append(f"G0 X0.00 Y0.00 F{feed_travel} ; Return to home origin\n")
    else:
        lines.append("; Resume directly from current / touched position (origin return skipped)\n")

    pages_to_render = [pages[page_index]] if (page_index is not None and 0 <= page_index < len(pages)) else pages

    for p_idx, page in enumerate(pages_to_render):
        page_num = page.get("page_number", p_idx + 1)
        p_width = page.get("width", 155.0)
        p_height = page.get("height", 200.0)
        lines.append(f"; ----------------- PAGE {page_num} -----------------")

        strokes = page.get("strokes_points", [])
        if not strokes:
            lines.append("; (Page is empty)")
            continue

        in_draw = False

        for pt in strokes:
            x, y, penup = pt[0], pt[1], pt[2]
            actual_x = (p_width - x) if flip_lab_record else x
            actual_y = (y if invert_y else (p_height - y)) if flip_lab_record else ((p_height - y) if invert_y else y)

            if penup > 0:
                # Need to lift pen if not already up
                if in_draw:
                    if pen_mode == "servo":
                        lines.append(pen_up_cmd)
                        if servo_delay_ms > 0:
                            lines.append(f"G4 P{servo_delay_ms / 1000.0:.2f}")
                    else:
                        lines.append(f"G0 Z{z_up_pos:.2f}")
                    in_draw = False

                # Travel move
                lines.append(f"G0 X{actual_x:.2f} Y{actual_y:.2f} F{feed_travel}")
            else:
                # Need to lower pen if not already down
                if not in_draw:
                    # Move to start position first
                    lines.append(f"G0 X{actual_x:.2f} Y{actual_y:.2f} F{feed_travel}")
                    if pen_mode == "servo":
                        lines.append(pen_down_cmd)
                        if servo_delay_ms > 0:
                            lines.append(f"G4 P{servo_delay_ms / 1000.0:.2f}")
                    else:
                        lines.append(f"G1 Z{z_down_pos:.2f} F{feed_draw}")
                    in_draw = True
                else:
                    # Draw line
                    lines.append(f"G1 X{actual_x:.2f} Y{actual_y:.2f} F{feed_draw}")

        # Ensure pen is up at end of page
        if in_draw:
            if pen_mode == "servo":
                lines.append(pen_up_cmd)
                if servo_delay_ms > 0:
                    lines.append(f"G4 P{servo_delay_ms / 1000.0:.2f}")
            else:
                lines.append(f"G0 Z{z_up_pos:.2f}")
            in_draw = False

        if return_to_origin:
            lines.append(f"G0 X0.00 Y0.00 F{feed_travel} ; Return to origin")
        else:
            lines.append("; End of page - hold position with pen UP (origin return skipped)")

        # If more pages remain in combined stream, pause for paper reload
        if p_idx < len(pages_to_render) - 1:
            lines.append("\n; PAUSE: Change paper sheet on the machine")
            lines.append("M0 (CHANGE PAPER - Press Resume to Continue)\n")

    lines.append("\n; End of job")
    if pen_mode == "servo":
        lines.append(pen_up_cmd)
    else:
        lines.append(f"G0 Z{z_up_pos:.2f}")
    if return_to_origin:
        lines.append(f"G0 X0.00 Y0.00 F{feed_travel} ; Return to origin")
    lines.append("M2           ; Program End")

    return "\n".join(lines)
